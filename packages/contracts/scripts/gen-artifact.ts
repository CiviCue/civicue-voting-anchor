// Writes ts/artifact.ts from the forge build output: the AnchorRegistry creation bytecode and
// the build information a deployment record needs. Run by `pnpm build` after `forge build`.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");

interface ForgeArtifact {
  bytecode: { object: string };
  metadata: { compiler: { version: string } };
}

const artifact = JSON.parse(
  readFileSync(
    join(root, "out", "AnchorRegistry.sol", "AnchorRegistry.json"),
    "utf8",
  ),
) as ForgeArtifact;

const git = (...args: string[]) =>
  execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
const gitCommit = git("rev-parse", "HEAD");
const gitDirty =
  git(
    "status",
    "--porcelain",
    "--untracked-files=no",
    "--",
    "src",
    "foundry.toml",
  ) !== "";

const out = `// Generated by scripts/gen-artifact.ts from the forge build output. Do not edit.
import type { Hex } from "viem";

/** AnchorRegistry creation bytecode, without constructor arguments. */
export const anchorRegistryBytecode: Hex = ${JSON.stringify(artifact.bytecode.object)};

/** How the bytecode was built: compiler version and the source commit. */
export const anchorRegistryBuild = {
  solcVersion: ${JSON.stringify(artifact.metadata.compiler.version)},
  gitCommit: ${JSON.stringify(gitCommit)},
  /** True when \`src/\` or \`foundry.toml\` had uncommitted changes at build time. */
  gitDirty: ${gitDirty},
} as const;
`;
writeFileSync(join(root, "ts", "artifact.ts"), out);
